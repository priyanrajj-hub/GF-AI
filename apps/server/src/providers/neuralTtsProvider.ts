import { MsEdgeTTS, OUTPUT_FORMAT } from 'msedge-tts'
import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'

export interface NeuralTTSOptions {
  voice?: string
  rate?: number // e.g. 1.0
  pitch?: number // e.g. 1.0
  language?: string
}

/**
 * High-Fidelity Neural Voice Provider (Zero Quota, Zero Robotic WebSpeech)
 * Uses Microsoft Edge Neural Voice API for 100% natural, human-sounding studio speech.
 * 
 * Recommended Voices:
 * - 'ta-IN-PallaviNeural' (Authentic, natural female Tamil voice)
 * - 'en-IN-NeerjaExpressiveNeural' (Expressive Indian English / Tanglish voice)
 * - 'en-US-AnaNeural' (Sweet, warm, young human girl voice - ideal for Mira / Yor companion)
 * - 'en-US-JennyNeural' (Friendly, warm, expressive tutor - ideal for Ada Coach & Tutor)
 * - 'en-US-ChristopherNeural' (Charismatic, confident male voice - ideal for Atlas / Tony Stark)
 */
export class NeuralTTSProvider {
  private static instance: NeuralTTSProvider

  public static getInstance(): NeuralTTSProvider {
    if (!NeuralTTSProvider.instance) {
      NeuralTTSProvider.instance = new NeuralTTSProvider()
    }
    return NeuralTTSProvider.instance
  }

  /**
   * Synthesize text into high quality MP3 audio base64
   */
  async synthesize(
    text: string,
    options: NeuralTTSOptions = {}
  ): Promise<{ audioBase64: string; mimeType: string; voice: string }> {
    const cleanText = text
      .replace(/[*#_`~]/g, '') // strip markdown
      .replace(/https?:\/\/\S+/g, 'link')
      .trim()

    if (!cleanText) {
      throw new Error('No text to synthesize')
    }

    // Dynamic Voice Selection: Tamil, Tanglish, or English
    let voice = options.voice
    if (!voice) {
      const isTamilScript = /[\u0B80-\u0BFF]/.test(cleanText)
      const isTanglishOrIndian =
        options.language === 'tanglish' ||
        options.language === 'ta' ||
        /\b(?:vanakkam|eppadi|irukkeenga|padinga|romba|mudiyum|kavalapadadheenga|nalla|panren|pannunga|sapteengala|mudichidalaam|dhaan)\b/i.test(cleanText)

      if (isTamilScript || options.language === 'ta') {
        voice = 'ta-IN-PallaviNeural'
      } else if (isTanglishOrIndian) {
        voice = 'en-IN-NeerjaExpressiveNeural'
      } else {
        voice = 'en-US-AnaNeural'
      }
    }

    const tts = new MsEdgeTTS()
    await tts.setMetadata(voice, OUTPUT_FORMAT.AUDIO_24KHZ_48KBITRATE_MONO_MP3)

    const ttsOptions: Record<string, string> = {}
    if (options.rate && options.rate !== 1.0) {
      ttsOptions.rate = `${Math.round((options.rate - 1.0) * 100)}%`
    }
    if (options.pitch && options.pitch !== 1.0) {
      ttsOptions.pitch = `${Math.round((options.pitch - 1.0) * 50)}Hz`
    }

    const tempDir = path.join(os.tmpdir(), `ada_tts_${Date.now()}_${Math.random().toString(36).substring(2, 8)}`)
    fs.mkdirSync(tempDir, { recursive: true })

    try {
      let result: any = null
      try {
        result = Object.keys(ttsOptions).length > 0
          ? await tts.toFile(tempDir, cleanText, ttsOptions)
          : await tts.toFile(tempDir, cleanText)
      } catch {
        // Socket close event is safely expected when all audio chunks are transferred
      }

      // Check for audio.mp3 in temp directory
      const audioFile = (result && result.audioFilePath) || path.join(tempDir, 'audio.mp3')
      if (!fs.existsSync(audioFile) || fs.statSync(audioFile).size === 0) {
        throw new Error('Audio file was not generated by Neural TTS')
      }

      const buffer = fs.readFileSync(audioFile)
      return {
        audioBase64: buffer.toString('base64'),
        mimeType: 'audio/mpeg',
        voice,
      }
    } finally {
      try {
        fs.rmSync(tempDir, { recursive: true, force: true })
      } catch {}
    }
  }
}
